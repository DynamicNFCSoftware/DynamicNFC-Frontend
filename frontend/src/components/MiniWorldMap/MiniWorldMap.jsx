import { getRegion } from "../../config/regionConfig";
import "./MiniWorldMap.css";

// Dot-matrix world map for the region morph loaders. Land mask: 80 × 34 cells,
// equirectangular, longitude -168…178, latitude 76…-52 (generated once from global-land-mask).
// Drawn in a 200-unit-wide viewBox so the loaders' pulse rings (r 2.5 → 18) keep their scale.
const LAND = [
  "...........###...####..############..................#.....######.....##........",
  "..........#####.######....########.................#..###################.......",
  ".###################.###...######.........######..##############################",
  ".###################.###...###....##.....#######################################",
  ".################....##.....#...........###.##################################..",
  "........###########..####............##..##.###########################...##....",
  "........############.#####..........###.################################..#.....",
  "..........##############.##...........##################################........",
  "..........###############.............########.#######################.#........",
  "..........#############..............##...###########################...........",
  "...........###########...............####....######################...#.........",
  "............#########................#####.....####################..#..........",
  ".............#######................###############################.............",
  ".............####...#..............###############################..............",
  "...............##.#.##.............############.####...####.#####...............",
  "...............####................#################...###..###...#.............",
  "..................##...............###############......#....###..#.............",
  "...................#.####..........################.....#.......................",
  ".....................######.........##############.......#.......#.#............",
  ".....................######..............#########...........##.##..............",
  "....................#########............########.............#.###..##.........",
  "....................###########..........#######..............#...#...##.#......",
  ".....................##########...........######........................#.......",
  ".....................#########............######....................##.#........",
  "......................########...........#######.#.................#####........",
  ".......................#######............#####..#...............########.......",
  ".......................#####..............#####..#...............#########......",
  "......................######..............####...................#########......",
  "......................#####................###...................#########......",
  "......................####.............................................##.......",
  "......................###...............................................#.....#.",
  "......................##.....................................................#..",
  "......................##........................................................",
  "......................#.........................................................",
];
const COLS = 80;
const ROWS = LAND.length;
const STEP = 200 / COLS;
const toX = (lng) => ((lng + 168) / 346) * (COLS - 1) * STEP + STEP / 2;
const toY = (lat) => ((76 - lat) / 128) * (ROWS - 1) * STEP + STEP / 2;

const DOTS = LAND.flatMap((row, r) =>
  [...row].flatMap((ch, c) => (ch === "#" ? [{ x: c * STEP + STEP / 2, y: r * STEP + STEP / 2 }] : []))
);

// Colour follows the region (same accent as the dashboard sidebar).
export default function MiniWorldMap({ region, lat, lng, ringRef, ring2Ref }) {
  const accent = getRegion(region).sidebarAccent;
  const px = toX(lng);
  const py = toY(lat);
  return (
    <svg viewBox={`0 0 200 ${ROWS * STEP}`} preserveAspectRatio="xMidYMid meet" className="mwm-svg" aria-hidden="true">
      {DOTS.map(({ x, y }) => {
        const d = Math.hypot(x - px, y - py) / STEP;
        const lit = d < 5.5;
        return <circle key={`${x}-${y}`} cx={x} cy={y} r="0.9" className={lit && d >= 3 ? "mwm-dot mwm-dot--glow" : "mwm-dot"} style={lit ? { fill: accent } : undefined} />;
      })}
      <circle ref={ring2Ref} cx={px} cy={py} r="3" fill="none" stroke={accent} strokeWidth="0.6" opacity="0" className="mwm-pin" />
      <circle ref={ringRef} cx={px} cy={py} r="2.5" fill="none" stroke={accent} strokeWidth="0.8" opacity="0.9" className="mwm-pin" />
      <circle cx={px} cy={py} r="2.4" fill={accent} className="mwm-pin" />
      <circle cx={px} cy={py} r="0.9" fill="#ffffff" className="mwm-pin" />
    </svg>
  );
}
